# Function to download a single stock safely
def download_stock(ticker):
    try:
        # history() returns clean OHLCV data without MultiIndex bugs
        df = yf.Ticker(ticker).history(period="5y")
        if len(df) > 1000: # Ensure we have at least ~4 years of data
            df['Ticker'] = ticker
            return df
    except Exception:
        pass
    return None

print("Downloading data using multi-threading (this takes ~45 seconds)...")
# Use 5 parallel threads to download safely and quickly
with concurrent.futures.ThreadPoolExecutor(max_workers=5) as executor:
    results = list(executor.map(download_stock, tickers))

# Combine all successful downloads
print("Combining and cleaning data...")
final_df = pd.concat([r for r in results if r is not None])

# Reset index to make Date a normal column
final_df = final_df.reset_index()

# Save to CSV
os.makedirs("data", exist_ok=True)
final_df.to_csv("data/ohlcv_data.csv", index=False)

